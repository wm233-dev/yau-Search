def meta_blob(r):
    return " | ".join(str(r.get(k) or '') for k in ('title','fn','author','series'))

def score(r):
    return (1 if r['text_layer'] else 0)*10000 + r['n_toc']

lines = []
for topic,(bkws,tocws) in TOPICS.items():
    lines.append("\n" + "="*90)
    lines.append(f"## {topic}")
    mb = {}
    for r in recs:
        if any(re.search(k, meta_blob(r), re.I) for k in bkws):
            t = re.sub(r'\s+','', r['title'])
            if t not in mb or score(r) > score(mb[t]): mb[t] = r
    mbl = sorted(mb.values(), key=lambda r: -score(r))
    lines.append(f"-- BOOKS ({len(mbl)}):")
    for r in mbl[:10]:
        lines.append(f"  [{r['id']}] {r['title']} | {r['author']} | {r['series']} | {r['publisher']} {r['year']} | toc={r['n_toc']} tl={r['text_layer']} pg={r['pages']}")
    tb = {}
    for r in recs:
        if r['n_toc'] < 10: continue
        m = [l for l in r['toc'] if any(re.search(k, l, re.I) for k in tocws)]
        if m:
            t = re.sub(r'\s+','', r['title'])
            if t not in tb or len(m) > len(tb[t][1]): tb[t] = (r, m)
    tbl = sorted(tb.values(), key=lambda x: -len(x[1]))
    lines.append(f"-- TOC BOOKS ({len(tbl)}):")
    for r, m in tbl[:8]:
        lines.append(f"  [{r['id']}] {r['title']} (toc={r['n_toc']}, hits={len(m)})")
        for l in m[:14]:
            lines.append(f"      - {l}")

open(OUT,'w',encoding='utf-8').write("\n".join(lines))
print("wrote", OUT, len(lines))
