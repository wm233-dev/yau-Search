o('>')
o('> where ε ∈ (0, 1) is a constant, and u_0(x) is a smooth periodic function of period 1.')
o('> (1) Prove that if u^ε(x, t) is a solution to (B), then u^ε(x, t) is uniformly bounded independent of ε.')
o('> (2) Prove that the solution u^ε(x, t) is periodic in x with period 1.')
o('> (3) Show that if u^ε(x, t) is a solution to (B), then ∂_x u^ε(x, t) ≤ 1/t for all x ∈ R, t > 0.')
o('> (4) Show that the total variation of u^ε(x, t) in x is uniformly bounded independent of ε for t > 0,')
