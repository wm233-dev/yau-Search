o('5. (5) 是开放题，指向 ε → 0 时解收敛到熵解（无粘极限）。')
o('6. 自评难度 5：五个小问把「最大值原理 → 抛物唯一性 → 导数界 → BV 估计 → 无粘极限」串成一条完整链条，')
